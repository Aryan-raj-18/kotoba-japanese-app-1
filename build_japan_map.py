"""Build the offline SVG map data. Run with Python + shapely==2.1.2.

The bundled source datasets and their licences are in map_sources/.
All layers and the learning pins use the same Mercator projection.
"""
import json
import math
from pathlib import Path

from shapely.geometry import box, shape
from shapely.ops import unary_union

ROOT = Path(__file__).resolve().parent
WIDTH, HEIGHT = 760, 920
WEST, SOUTH, EAST, NORTH = 122.2, 23.4, 146.9, 46.4


def mercator(lat):
    return math.degrees(math.log(math.tan(math.pi / 4 + math.radians(lat) / 2)))


SCALE = min((WIDTH - 56) / (EAST - WEST), (HEIGHT - 84) / (mercator(NORTH) - mercator(SOUTH)))
LEFT = (WIDTH - (EAST - WEST) * SCALE) / 2
TOP = (HEIGHT - (mercator(NORTH) - mercator(SOUTH)) * SCALE) / 2


def project(lon, lat):
    return LEFT + (lon - WEST) * SCALE, TOP + (mercator(NORTH) - mercator(lat)) * SCALE


def polygons(geometry):
    if geometry.geom_type == "Polygon":
        yield geometry
    elif geometry.geom_type in ("MultiPolygon", "GeometryCollection"):
        for child in geometry.geoms:
            yield from polygons(child)


def path(geometry):
    commands = []
    for polygon in polygons(geometry):
        for ring in [polygon.exterior] + list(polygon.interiors):
            coords = [project(*point[:2]) for point in ring.coords]
            commands.append("M" + "L".join("{:.2f},{:.2f}".format(*p) for p in coords) + "Z")
    return "".join(commands)


def main():
    prefs = json.loads((ROOT / "map_sources/japan-prefectures.geojson").read_text())
    land = json.loads((ROOT / "map_sources/natural-earth-land.geojson").read_text())
    places = json.loads((ROOT / "data/japan_explorer.json").read_text())["places"]
    by_code = {p["code"]: p for p in places}
    assert len(prefs["features"]) == len(by_code) == 47
    viewport = box(WEST - 2, SOUTH - 2, EAST + 2, NORTH + 2)
    features = []
    japan_shapes = []
    for feature in prefs["features"]:
        code = int(feature["properties"]["shapeISO"].split("-")[-1])
        place = by_code[code]
        geometry = shape(feature["geometry"])
        japan_shapes.append(geometry)
        clipped = geometry.intersection(viewport)
        west, south, east, north = clipped.bounds
        x1, y1 = project(west, north)
        x2, y2 = project(east, south)
        features.append({"id": place["id"], "name": place["prefecture_en"], "path": path(clipped),
                         "bounds": [round(v, 2) for v in [x1, y1, x2, y2]]})
    japan = unary_union(japan_shapes).buffer(.04)
    surrounding = []
    for feature in land["features"]:
        geometry = shape(feature["geometry"])
        if not geometry.intersects(viewport) or japan.contains(geometry.representative_point()):
            continue
        surrounding.append(path(geometry.intersection(viewport)))
    result = {"projection": {"width": WIDTH, "height": HEIGHT, "west": WEST, "north": NORTH,
                             "scale": SCALE, "left": LEFT, "top": TOP},
              "prefectures": sorted(features, key=lambda f: f["id"]), "surroundingLand": surrounding,
              "sources": {"prefectures": "geoBoundaries / OpenStreetMap, ODbL 1.0",
                          "land": "Natural Earth, public domain"}}
    target = ROOT / "static/js/japan_geography.js"
    target.write_text("// Generated by build_japan_map.py; see map_sources/README.md for attribution.\n"
                      "window.JAPAN_GEOGRAPHY = " + json.dumps(result, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("Generated", len(features), "prefectures;", target.stat().st_size, "bytes")


if __name__ == "__main__":
    main()
